import json
import uuid

import httpx

from src.config.base import BaseConfig


class OllamaService:
    async def analyze_document(self, text: str) -> tuple[str, str]:
        prompt = (
            "Ты — анализатор официальных российских документов.\n"
            "Из текста ниже извлеки два значения.\n\n"

            "=== 1. org — ведомство или подразделение, составившее документ ===\n"
            "Правила (применяй по порядку, остановись на первом совпадении):\n"
            "  а) ГИБДД: выполни оба условия одновременно, проверяя ВЕСЬ текст целиком (не только шапку):\n"
            "     — условие 1: где угодно в тексте встречается «МВД» (в любом регистре, в любой части документа);\n"
            "     — условие 2: где угодно в тексте (в теле документа, в реквизитах, в любом абзаце) встречается\n"
            "       хотя бы одно из слов: ГИБДД, Госавтоинспекция, транспортное средство, автомобиль,\n"
            "       водительское удостоверение, регистрационный знак, ПТС, ДТП, ОСАГО, дорожно-транспортный.\n"
            "     Если оба условия выполнены → верни «ГИБДД».\n"
            "  б) МВД: если в документе есть «МВД», но ни одного слова из условия 2 нет нигде в тексте → верни «МВД».\n"
            "  в) Иначе — верни краткое название: МЧС, ФНС, ФССП, ФСБ, СК, Росреестр, Прокуратура и т.п.\n\n"

            "=== 2. person — ФИО субъекта документа (тот, В ОТНОШЕНИИ кого документ) ===\n"
            "Признаки субъекта: рядом с именем есть «в отношении», «сведения о», «проверка», «на гражданина», «по запросу о».\n"
            "НЕ бери: адресата письма (кому направлено), подписанта, финансового управляющего, отправителя.\n\n"
            "Правила приведения к именительному падежу с учётом рода:\n"
            "  • Определи пол по окончаниям:\n"
            "    — Мужской: фамилия на согласную/-й (Иванов, Петров); отчество на -ич/-ович/-евич.\n"
            "    — Женский: фамилия на -а/-я/-ая/-яя (Иванова, Петрова); отчество на -на/-овна/-евна.\n"
            "  • Преобразуй ФИО в именительный падеж с учётом рода:\n"
            "    «Иванова Ивана Ивановича» → «Иванов Иван Иванович» (муж.)\n"
            "    «Петровой Марии Ивановны» → «Петрова Мария Ивановна» (жен.)\n"
            "  • Формат: Фамилия Имя Отчество (если отчества нет — Фамилия Имя).\n\n"

            "Верни ТОЛЬКО JSON без пояснений: {\"org\": \"...\", \"person\": \"...\"}\n"
            "Если значение не удаётся определить — верни \"UNKNOWN\".\n\n"
            f"Текст документа:\n{text[:3000]}"
        )

        try:
            async with httpx.AsyncClient(timeout=120.0) as client:
                resp = await client.post(
                    f"{BaseConfig.OLLAMA_URL}/api/generate",
                    json={
                        "model": BaseConfig.OLLAMA_MODEL,
                        "prompt": prompt,
                        "stream": False,
                        "format": "json",
                    },
                )
                resp.raise_for_status()
                result = json.loads(resp.json().get("response", "{}"))
                org = (result.get("org") or "UNKNOWN").strip() or "UNKNOWN"
                person = (result.get("person") or "UNKNOWN").strip() or "UNKNOWN"
                return org, person
        except Exception as e:
            print(f"LLM analyze error: {e}")
            return "UNKNOWN", str(uuid.uuid4())
